package ethtest

import (
	"bytes"
	"strings"
	"testing"
)

func sampleResults() []Result {
	return []Result{
		{ID: "b::t::Prague::0", Fork: "Prague", Status: Pass},
		{ID: "a::t::Osaka::0", Fork: "Osaka", Status: Fail, Reason: "root"},
		{ID: "c::t::Cancun::0", Fork: "Cancun", Status: Fail, Reason: "unsupported: create tx"},
		{ID: "d::t::Cancun::1", Fork: "Cancun", Status: Fail, Reason: "logs"},
		{ID: "e::t::Cancun::2", Fork: "Cancun", Status: Error, Reason: "panic: x"},
		{ID: "f::t::ShanghaiToCancunAtTime15k::0", Fork: "ShanghaiToCancunAtTime15k", Status: Pass},
		{ID: "i::t::Cancun::5", Fork: "Cancun", Status: Pass, Reason: "rejected"},
		{ID: "g::t::Cancun::3", Fork: "Cancun", Status: Fail, Reason: "timeout"},
		{ID: "h::t::Cancun::4", Fork: "Cancun", Status: Fail, Reason: "crash: panic: x"},
	}
}

func TestScoreboardForkOrder(t *testing.T) {
	out := string(Scoreboard(sampleResults(), "tests@v21.0.2", "abc"))
	cancun, prague, osaka := strings.Index(out, "| Cancun "), strings.Index(out, "| Prague "), strings.Index(out, "| Osaka ")
	transition := strings.Index(out, "| ShanghaiToCancunAtTime15k ")
	if cancun < 0 || prague < 0 || osaka < 0 || transition < 0 {
		t.Fatalf("missing fork rows:\n%s", out)
	}
	if !(cancun < prague && prague < osaka && osaka < transition) {
		t.Fatalf("fork order wrong:\n%s", out)
	}
}

func TestScoreboardCounts(t *testing.T) {
	out := string(Scoreboard(sampleResults(), "tests@v21.0.2", "abc"))
	// Only deterministic classes: fork | total | pass | of which rejected | fail | unsupported | error | pass %
	if !strings.Contains(out, "| Cancun | 6 | 1 | 1 | 3 | 1 | 1 | 16.7% |") {
		t.Fatalf("Cancun row wrong:\n%s", out)
	}
	if !strings.Contains(out, "| **Total** | 9 | 3 | 1 | 4 | 1 | 1 | 33.3% |") {
		t.Fatalf("total row wrong:\n%s", out)
	}
	if strings.Contains(out, "timeout") || strings.Contains(out, "crash") {
		t.Fatalf("scoreboard shows a time- or memory-dependent class:\n%s", out)
	}
	if !strings.Contains(out, "tests@v21.0.2") || !strings.Contains(out, "abc") {
		t.Fatalf("release or sha missing:\n%s", out)
	}
	if !strings.HasPrefix(out, "<!-- generated by cmd/ethtest; do not edit -->") {
		t.Fatalf("generated header missing:\n%s", out)
	}
}

func TestBreakdown(t *testing.T) {
	got := Breakdown(sampleResults())
	want := "pass 2, pass (rejected tx) 1, root 1, logs 1, timeout 1, crash 1, unsupported 1, error 1"
	if got != want {
		t.Fatalf("Breakdown = %q, want %q", got, want)
	}
}

func TestScoreboardStable(t *testing.T) {
	a := Scoreboard(sampleResults(), "r", "s")
	reversed := sampleResults()
	for i, j := 0, len(reversed)-1; i < j; i, j = i+1, j-1 {
		reversed[i], reversed[j] = reversed[j], reversed[i]
	}
	if !bytes.Equal(a, Scoreboard(reversed, "r", "s")) {
		t.Fatal("scoreboard depends on result order")
	}
}

func TestPassingListSorted(t *testing.T) {
	got := string(PassingList(sampleResults()))
	want := "b::t::Prague::0\nf::t::ShanghaiToCancunAtTime15k::0\ni::t::Cancun::5\n"
	if got != want {
		t.Fatalf("PassingList = %q, want %q", got, want)
	}
}

func TestRegressions(t *testing.T) {
	prev := []string{"b::t::Prague::0", "a::t::Osaka::0", "gone::t::Cancun::0"}
	got := Regressions(prev, sampleResults())
	want := []string{"a::t::Osaka::0", "gone::t::Cancun::0"}
	if strings.Join(got, ",") != strings.Join(want, ",") {
		t.Fatalf("Regressions = %v, want %v", got, want)
	}
}
