package ethtest

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// forkOrder is Ethereum's fork sequence. Forks not listed (transition forks,
// future forks) sort alphabetically after these.
var forkOrder = []string{
	"Frontier", "Homestead", "TangerineWhistle", "SpuriousDragon", "Byzantium",
	"Constantinople", "ConstantinopleFix", "Istanbul", "Berlin", "London",
	"Paris", "Shanghai", "Cancun", "Prague", "Osaka", "Amsterdam",
}

// forkCounts holds only classes that do not depend on machine speed or
// memory: a slow or crashing case is a failure whether it ends as a wrong
// root, a timeout or a crash.
type forkCounts struct {
	total, pass, rejected, fail, unsupported, errors int
}

func (c *forkCounts) add(r Result) {
	c.total++
	switch {
	case r.Status == Pass:
		c.pass++
		if r.Reason == "rejected" {
			c.rejected++
		}
	case r.Status == Error:
		c.errors++
	case strings.HasPrefix(r.Reason, "unsupported"):
		c.unsupported++
	default:
		c.fail++
	}
}

func (c forkCounts) row(name string) string {
	pct := 0.0
	if c.total > 0 {
		pct = 100 * float64(c.pass) / float64(c.total)
	}
	return fmt.Sprintf("| %s | %d | %d | %d | %d | %d | %d | %.1f%% |\n",
		name, c.total, c.pass, c.rejected, c.fail, c.unsupported, c.errors, pct)
}

// breakdownOrder lists the reason classes Breakdown reports, in order.
var breakdownOrder = []string{"pass", "pass (rejected tx)", "root", "logs", "exception", "sender", "timeout", "crash", "unsupported", "error"}

// Breakdown summarises results by reason class, including the time- and
// memory-dependent classes the scoreboard leaves out.
func Breakdown(results []Result) string {
	counts := make(map[string]int)
	for _, r := range results {
		switch {
		case r.Status == Pass && r.Reason == "rejected":
			counts["pass (rejected tx)"]++
		case r.Status == Pass:
			counts["pass"]++
		case r.Status == Error:
			counts["error"]++
		default:
			class := r.Reason
			if i := strings.Index(class, ":"); i >= 0 {
				class = class[:i]
			}
			counts[class]++
		}
	}
	var parts []string
	for _, class := range breakdownOrder {
		if n := counts[class]; n > 0 {
			parts = append(parts, fmt.Sprintf("%s %d", class, n))
		}
	}
	return strings.Join(parts, ", ")
}

func sortForks(forks []string) {
	rank := make(map[string]int, len(forkOrder))
	for i, f := range forkOrder {
		rank[f] = i
	}
	sort.Slice(forks, func(i, j int) bool {
		ri, oki := rank[forks[i]]
		rj, okj := rank[forks[j]]
		switch {
		case oki && okj:
			return ri < rj
		case oki != okj:
			return oki
		default:
			return forks[i] < forks[j]
		}
	})
}

// Scoreboard renders per-fork results as Markdown. The output depends only on
// the results and the fixture release, so it is byte-stable between runs.
func Scoreboard(results []Result, release, sha string) []byte {
	byFork := make(map[string]*forkCounts)
	var total forkCounts
	for _, r := range results {
		c := byFork[r.Fork]
		if c == nil {
			c = &forkCounts{}
			byFork[r.Fork] = c
		}
		c.add(r)
		total.add(r)
	}
	forks := make([]string, 0, len(byFork))
	for f := range byFork {
		forks = append(forks, f)
	}
	sortForks(forks)

	var b bytes.Buffer
	b.WriteString("<!-- generated by cmd/ethtest; do not edit -->\n")
	b.WriteString("# Ethereum state test conformance\n\n")
	fmt.Fprintf(&b, "Fixtures: `ethereum/execution-specs` `%s` (sha256 `%s`)\n\n", release, sha)
	b.WriteString("\"Pass: rejected tx\" counts passes where Ethereum rejects the transaction and Burrow\n")
	b.WriteString("rejects it for the same reason. They are included in Pass.\n\n")
	b.WriteString("| Fork | Total | Pass | Pass: rejected tx | Fail | Unsupported | Error | Pass % |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|\n")
	for _, f := range forks {
		b.WriteString(byFork[f].row(f))
	}
	b.WriteString(total.row("**Total**"))
	return b.Bytes()
}

// PassingList returns the IDs of passing cases, sorted, one per line.
func PassingList(results []Result) []byte {
	var ids []string
	for _, r := range results {
		if r.Status == Pass {
			ids = append(ids, r.ID)
		}
	}
	sort.Strings(ids)
	if len(ids) == 0 {
		return nil
	}
	return []byte(strings.Join(ids, "\n") + "\n")
}

// Regressions returns the IDs in prev that did not pass in results, including
// IDs that no longer exist.
func Regressions(prev []string, results []Result) []string {
	passed := make(map[string]bool, len(results))
	for _, r := range results {
		if r.Status == Pass {
			passed[r.ID] = true
		}
	}
	var out []string
	for _, id := range prev {
		if !passed[id] {
			out = append(out, id)
		}
	}
	return out
}
